/**
 * Builds the final technical documentation from the chapter sources:
 *   docs/FINAL_DOCUMENTATION.md          (editable, assembled Markdown)
 *   docs/build/final-documentation.html  (print-ready HTML, Mermaid diagrams rendered in the browser)
 *   docs/MariStay_Final_Documentation.pdf (if Microsoft Edge or Google Chrome is installed)
 *
 * Usage: npm run docs:build
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const { Marked } = require('marked');

const ROOT = path.resolve(__dirname, '..');
const DOCS = path.join(ROOT, 'docs');
const BUILD = path.join(DOCS, 'build');

// Chapter order required by the Final Project guidelines (§3.7).
const CHAPTERS = [
  { file: 'final/01-project-overview.md', title: 'Project Overview' },
  { file: 'final/02-system-analysis.md', title: 'System Analysis' },
  { file: 'SYSTEM_ARCHITECTURE.md', title: 'System Architecture' },
  { file: 'DATABASE_DESIGN.md', title: 'Database Design' },
  { file: 'API_DOCUMENTATION.md', title: 'REST API Design' },
  { file: 'AUTHENTICATION_SECURITY.md', title: 'Authentication and Security' },
  { file: 'final/07-backend-implementation.md', title: 'Backend Implementation' },
  { file: 'TESTING_REPORT.md', title: 'API Testing and Validation' },
  { file: 'final/09-conclusion.md', title: 'Conclusion' },
  { file: 'final/10-references.md', title: 'References', unnumbered: true },
  { file: 'final/11-appendix.md', title: 'Appendix', unnumbered: true },
];

const read = (rel) => fs.readFileSync(path.join(DOCS, rel), 'utf8').replace(/\r\n/g, '\n');
const slug = (text) =>
  text.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^\p{L}\p{N}\s-]/gu, '').trim().replace(/\s+/g, '-');

// ---------- 1. Assemble Markdown ----------
let chapterNo = 0;
const toc = [];
const bodies = CHAPTERS.map((chapter) => {
  let text = read(chapter.file);
  // Links in docs/final/*.md are relative to docs/final; the assembled file lives in docs/.
  if (chapter.file.startsWith('final/')) text = text.replace(/\]\(\.\.\/\.\.\//g, '](../');
  const heading = chapter.unnumbered ? chapter.title : `Chapter ${++chapterNo} — ${chapter.title}`;
  text = text.replace(/^# .*$/m, `# ${heading}`);
  toc.push(`- [${heading}](#${slug(heading)})`);
  for (const m of text.matchAll(/^## (.+)$/gm)) toc.push(`  - [${m[1]}](#${slug(m[1])})`);
  return text.trim();
});

const markdown = [
  '<!-- GENERATED by `npm run docs:build` from docs/final/*.md and the docs/*.md chapters. Edit those files, not this one. -->',
  read('final/00-cover.md').trim(),
  '<div class="page-break"></div>\n\n# Table of Contents\n\n' + toc.join('\n'),
  ...bodies.map((b) => '<div class="page-break"></div>\n\n' + b),
].join('\n\n') + '\n';
fs.writeFileSync(path.join(DOCS, 'FINAL_DOCUMENTATION.md'), markdown);
console.log('✔ docs/FINAL_DOCUMENTATION.md');

// ---------- 2. Render HTML ----------
const escapeHtml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const marked = new Marked({
  gfm: true,
  renderer: {
    code({ text, lang }) {
      if (lang === 'mermaid') return `<pre class="mermaid">${escapeHtml(text)}</pre>\n`;
      return `<pre><code class="language-${lang ?? 'text'}">${escapeHtml(text)}</code></pre>\n`;
    },
    heading({ tokens, depth }) {
      const inner = this.parser.parseInline(tokens);
      return `<h${depth} id="${slug(inner)}">${inner}</h${depth}>\n`;
    },
  },
});
const mermaidPath = path.relative(BUILD, path.join(ROOT, 'node_modules/mermaid/dist/mermaid.min.js')).replace(/\\/g, '/');
const html = `<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>MariStay — Technical Documentation</title>
<style>
  @page { size: A4; margin: 18mm 16mm; }
  body { font-family: "Segoe UI", Calibri, Arial, sans-serif; font-size: 10.5pt; line-height: 1.45; color: #1b2433; }
  h1 { color: #1f3a5f; border-bottom: 2px solid #c9a227; padding-bottom: 4px; font-size: 20pt; }
  h2 { color: #1f3a5f; font-size: 14pt; margin-top: 1.4em; }
  h3 { color: #2c4a73; font-size: 12pt; }
  table { border-collapse: collapse; width: 100%; margin: .6em 0; font-size: 9pt; page-break-inside: auto; }
  tr { page-break-inside: avoid; }
  th, td { border: 1px solid #b8c2d1; padding: 3px 6px; vertical-align: top; text-align: left; }
  th { background: #e8edf5; }
  code { font-family: Consolas, "Courier New", monospace; font-size: 8.8pt; background: #f3f5f9; padding: 0 2px; }
  pre { background: #f3f5f9; border: 1px solid #dde3ec; padding: 6px 8px; white-space: pre-wrap; word-break: break-word; font-size: 8.4pt; }
  pre code { background: none; padding: 0; }
  pre.mermaid { background: #fff; border: none; text-align: center; page-break-inside: avoid; }
  .page-break { page-break-before: always; }
  .cover { text-align: center; padding-top: 50mm; }
  .cover h1 { border: none; font-size: 26pt; }
  .cover table { width: 75%; margin: 18mm auto 0; font-size: 11pt; }
  .cover td { border: none; border-bottom: 1px solid #dde3ec; padding: 6px; }
  a { color: #1f4f8f; text-decoration: none; }
</style></head>
<body>
${marked.parse(markdown.replace(/^<!--.*-->\n/, ''))}
<script src="${mermaidPath}"></script>
<script>mermaid.initialize({ startOnLoad: true, theme: 'neutral', securityLevel: 'strict', flowchart: { useMaxWidth: true } });</script>
</body></html>`;
fs.mkdirSync(BUILD, { recursive: true });
const htmlFile = path.join(BUILD, 'final-documentation.html');
fs.writeFileSync(htmlFile, html);
console.log('✔ docs/build/final-documentation.html');

// ---------- 3. Print PDF with a headless Chromium browser (if available) ----------
const browsers = [
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
];
const browser = browsers.find((b) => fs.existsSync(b));
if (!browser) {
  console.log('ℹ No Edge/Chrome found — open docs/build/final-documentation.html and print it to PDF manually.');
  process.exit(0);
}
const pdf = path.join(DOCS, 'MariStay_Final_Documentation.pdf');
execFileSync(browser, [
  '--headless=new',
  '--disable-gpu',
  '--no-pdf-header-footer',
  '--allow-file-access-from-files',
  '--virtual-time-budget=30000',
  `--print-to-pdf=${pdf}`,
  'file:///' + htmlFile.replace(/\\/g, '/'),
], { stdio: 'ignore', timeout: 120000 });
console.log(`✔ docs/MariStay_Final_Documentation.pdf (${Math.round(fs.statSync(pdf).size / 1024)} KB)`);
